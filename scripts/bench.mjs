// Precision and recall per rule on a labeled benchmark.
//
//   npm run bench               print the table
//   npm run bench -- --write    also write bench/RESULTS.md
//
// Each file in bench/cases starts with `// expect: MS011, MS019` (or `none`):
// the rules a careful reviewer would want reported for that file. Cases come in
// three kinds: the plain vulnerable pattern, variants written to be harder to
// catch (aliases, helpers, other names), and safe code that looks similar. A
// rule reported on a file that does not expect it counts as a false positive;
// an expected rule that is not reported counts as a missed finding.

import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { lintFiles } from "../dist/src/node.js";

const dir = "bench/cases";
const files = readdirSync(dir).filter((f) => /\.(compact|tsx?)$/.test(f)).sort();
const stats = new Map();
const row = (id) => stats.get(id) ?? (stats.set(id, { tp: 0, fp: 0, fn: 0 }), stats.get(id));
const misses = [];
const falsePositives = [];

for (const f of files) {
  const path = join(dir, f);
  const text = readFileSync(path, "utf8");
  const expect = new Set((text.match(/^\/\/ expect: (.*)$/m)?.[1] ?? "none").split(",").map((s) => s.trim()).filter((s) => s && s !== "none"));
  const note = text.match(/^\/\/ note: (.*)$/m)?.[1];
  const got = new Set(lintFiles([path]).filter((x) => x.ruleId !== "MS000" && x.ruleId !== "MS006").map((x) => x.ruleId));
  for (const id of expect) {
    if (got.has(id)) row(id).tp++;
    else {
      row(id).fn++;
      misses.push({ file: f, id, note });
    }
  }
  for (const id of got) {
    if (expect.has(id)) continue;
    row(id).fp++;
    falsePositives.push({ file: f, id });
  }
}

const pct = (a, b) => (b === 0 ? "–" : `${Math.round((100 * a) / b)}%`);
const ids = [...stats.keys()].sort();
const total = ids.reduce((s, id) => ({ tp: s.tp + stats.get(id).tp, fp: s.fp + stats.get(id).fp, fn: s.fn + stats.get(id).fn }), { tp: 0, fp: 0, fn: 0 });
const lines = [
  "| Rule | Found | Missed | False positives | Precision | Recall |",
  "| --- | ---: | ---: | ---: | ---: | ---: |",
  ...ids.map((id) => {
    const s = stats.get(id);
    return `| ${id} | ${s.tp} | ${s.fn} | ${s.fp} | ${pct(s.tp, s.tp + s.fp)} | ${pct(s.tp, s.tp + s.fn)} |`;
  }),
  `| **All** | **${total.tp}** | **${total.fn}** | **${total.fp}** | **${pct(total.tp, total.tp + total.fp)}** | **${pct(total.tp, total.tp + total.fn)}** |`,
];
const summary = `${files.length} labeled files: ${total.tp} expected findings reported, ${total.fn} missed, ${total.fp} false positives.`;

console.log(summary + "\n");
console.log(lines.join("\n"));
if (misses.length) console.log("\nMissed:\n" + misses.map((m) => `  ${m.id}  ${m.file}${m.note ? `  (${m.note})` : ""}`).join("\n"));
if (falsePositives.length) console.log("\nFalse positives:\n" + falsePositives.map((m) => `  ${m.id}  ${m.file}`).join("\n"));

if (process.argv.includes("--write")) {
  const md = `# Benchmark results

Generated by \`npm run bench -- --write\`. ${summary}

The cases in [cases/](cases/) are written by the project author: the plain vulnerable pattern for each rule, variants made to be harder to catch (aliases, helper circuits, other names), and safe code that looks similar. They are not compiled with the Compact compiler. Treat the numbers as a regression check and an honest list of known misses, not as an independent audit. New cases, especially ones that break a rule, are welcome.

${lines.join("\n")}

## Known misses

${misses.length ? misses.map((m) => `- **${m.id}** \`${m.file}\`${m.note ? `: ${m.note}` : ""}`).join("\n") : "None."}

## False positives

${falsePositives.length ? falsePositives.map((m) => `- **${m.id}** \`${m.file}\``).join("\n") : "None."}
`;
  writeFileSync("bench/RESULTS.md", md);
}
